#!/usr/bin/env python3
"""source_map.py — 线上 URL → 站点仓库里生成它的源文件(RQ-229;stdlib only,只读仓库)。

支持两类站(其他框架给「不支持」,不猜):
  - Next.js App Router:`app/`(或 src/app、web/app 等)下的 page.{tsx,ts,jsx,js,mdx};认路由组 (group)、
    动态段 [x]、捕获段 [...x] / [[...x]],跳过 _private 和 @slot。
  - 纯静态站:a/b → a/b/index.html、a/b.html(仓库根、public/、dist/、site/、docs/ 下)。

先看页面本身(默认开,--no-fetch 关):抓线上页面的 title、meta description、H1、og:title 和首段,切成片段在
仓库里反查原文,按「片段越少见越可信」给文件打分;路由 import 闭包里的文件加分,语言目录对不上的减分。这是行家
找真源的办法——标题写在哪个文件,就改哪个文件。页面抓不到、原文在仓库里一条都搜不到(标题是模板拼的)时,
退回下面的路由 + 动态段办法。

模板拼的标题(「{平台}{能力}爬虫 API」)要先把原文拆成「措辞 + 数据值」:路由 import 链里的模板固定部分和写死的
字面量(含 `${...}` 表达式里的)是措辞;URL 实体词、生成物里的表值、模板空位里填的短名字是数据值。只撞上数据值的
文件(正文里恰好提到这个名字的指南、博客)不算证据;解释措辞最多的模板文件得分。第一名给模板,名字所在数据表的
真源(生成器、上游数据文件)列为 data-value 候选,并在结果里给出 combo = {template, data}。

动态页还要找「数据从哪来」:在仓库里按动态段的值(及去掉 -api / -scraper 等尾巴的词根)搜数据文件。
搜到的文件开头写着「自动生成 / generated / DO NOT EDIT」时,它是生成物,改它会被覆盖:顺着头部注释里提到的
脚本路径找生成器,把生成器列为真源。

每个候选带置信度(0–1)和角色(route 路由文件 / data 数据 / generator 生成器 / generated 生成物,不要手改)。
最高置信度低于 --min-confidence(默认 0.7)时 `actionable=false`:只列候选,不该动手改。

读仓库:默认工作树;--rev REV 时用 `git ls-tree` / `git grep` 读那个提交(不用检出)。

用法:
  python3 source_map.py --repo PATH [--rev origin/main] [--json] URL [URL...]
退出码:0 正常;2 用法错误。
"""
