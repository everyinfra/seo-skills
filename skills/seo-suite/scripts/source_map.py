class Repo:
    def __init__(self, path, rev=None):
        self.path, self.rev = path, rev
        self._files = None
        self._corpus = {}
        self._strings = {}
        self._gen = {}

    def strings(self, path):
        """→ (字面量, 模板):文件里写死的文字和带空位的模板字符串,按文件缓存。"""
        if path not in self._strings:
            self._strings[path] = js_strings(self.read(path)) if path.endswith(CODE_EXT) else ([], [])
        return self._strings[path]

    def generated(self, path):
        if path not in self._gen:
            self._gen[path] = bool(GEN_MARK.search(self.head(path)))
        return self._gen[path]

    def git(self, *args):
        p = subprocess.run(["git", "-C", self.path, *args], capture_output=True, text=True, encoding="utf-8",
                           errors="replace")
        return p.stdout if p.returncode in (0, 1) else ""

    def files(self):
        if self._files is None:
            out = self.git("ls-tree", "-r", "-z", "--name-only", self.rev) if self.rev else self.git("ls-files", "-z")
            files = [f for f in out.split("\0") if f]              # -z:中文路径不被转义
            if not files and not self.rev:                     # 不是 git 仓库(比如构建产物目录):直接走目录
                for root, dirs, names in os.walk(self.path):
                    dirs[:] = [d for d in dirs if d not in SKIP_SEGS and not d.startswith(".")]
                    rel = os.path.relpath(root, self.path)
                    files += [n if rel == "." else rel + "/" + n for n in names]
            self._files = [f for f in files if f and not skipped(f)]
        return self._files

    def head(self, path, n=6):
        if self.rev:
            text = self.git("show", "%s:%s" % (self.rev, path))
        else:
            try:
                with open(os.path.join(self.path, path), encoding="utf-8", errors="replace") as f:
                    text = f.read(4000)
            except OSError:
                text = ""
        return "\n".join(text.splitlines()[:n])

    def read(self, path):
        if self.rev:
            return self.git("show", "%s:%s" % (self.rev, path))
        try:
            with open(os.path.join(self.path, path), encoding="utf-8", errors="replace") as f:
                return f.read()
        except OSError:
            return ""

    def grep_fixed(self, needle, limit=30, exts=DATA_EXT):
        if not self.rev and not self.git("rev-parse", "--is-inside-work-tree").strip():
            return self._walk_grep(needle, limit, exts)            # 不是 git 仓库:逐个文件读
        args = ["grep", "-l", "-F", "-e", needle]
        if self.rev:
            args.append(self.rev)
        args += ["--"] + ["*%s" % e for e in exts]
        out = self.git(*args)
        res = []
        for line in out.splitlines():
            f = line.split(":", 1)[1] if self.rev and ":" in line else line
            if not skipped(f):
                res.append(f)
            if len(res) >= limit:
                break
        return res

    def corpus(self, prefix=""):
        """prefix 下所有文本文件 → {路径: 内容},一次读进内存(单文件超过 MAX_FILE 跳过)。"""
        if prefix in self._corpus:
            return self._corpus[prefix]
        files = {f for f in self.files() if f.startswith(prefix) and f.endswith(TEXT_EXT)}
        out = {}
        if self.rev:
            listing = self.git("ls-tree", "-r", "-l", "-z", self.rev, "--", prefix or ".")
            blobs = {}
            for line in listing.split("\0"):
                meta, _, path = line.partition("\t")
                parts = meta.split()
                if len(parts) == 4 and parts[1] == "blob" and path in files and parts[3].isdigit() \
                        and int(parts[3]) <= MAX_FILE:
                    blobs.setdefault(parts[2], []).append(path)
            p = subprocess.run(["git", "-C", self.path, "cat-file", "--batch"], input="\n".join(blobs).encode(),
                               capture_output=True)
            data, i = p.stdout, 0
            while i < len(data):
                nl = data.find(b"\n", i)
                head = data[i:nl].split() if nl >= 0 else []
                if len(head) < 3:
                    break
                size = int(head[2])
                text = data[nl + 1: nl + 1 + size].decode("utf-8", "replace")
                for path in blobs.get(head[0].decode(), []):      # 内容相同的几个文件共用一个 blob
                    out[path] = text
                i = nl + 1 + size + 1
        else:
            for f in files:
                try:
                    if os.path.getsize(os.path.join(self.path, f)) <= MAX_FILE:
                        out[f] = self.read(f)
                except OSError:
                    pass
        self._corpus[prefix] = out
        return out

    def _walk_grep(self, needle, limit, exts):
        res = []
        for f in self.files():
            if f.endswith(exts) and needle in self.read(f):
                res.append(f)
                if len(res) >= limit:
                    break
        return res


