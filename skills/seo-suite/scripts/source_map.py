def explain(repo, files, text, words):
    """closure 里每个文件写死的字面量和模板,能解释这段原文里多少「措辞」(去掉数据值以后)。
    数据值:URL 里的实体词、生成物里的表值(平台名、能力名)、模板空位里填的短名字。
    → ({文件: 解释了几成措辞}, [数据值], {数据值来自的生成物})。行家找标题真源就是这样分:名字来自数据表,句子骨架来自模板;
    要改标题的措辞去改模板,名字错了才去改数据表的真源。
    两条边界:模板的固定部分(措辞)优先,别的模板空位把它吞进去时那段不算数据;生成物里的字面量等于整段原文时,
    是整页内容被生成进去了(Markdown → 生成的 .ts),不是表值,留给片段反查去找上游的那份。"""
    n = len(text)
    if not n:
        return {}, [], set()
    ents = [w.lower() for w in words if w.lower() not in GENERIC_WORDS]
    data, glue, fills, marks, src = [False] * n, [False] * n, [], {}, {}
    for w in ents:
        for s, e in _occurrences(text, w, fold=True):
            _mark(data, s, e)
    for f in files:
        lits, tpls = repo.strings(f)
        if repo.generated(f):                          # 生成物里的表值:是数据,不是措辞
            for lit in {x.strip() for x in lits}:
                if wlen(lit) >= DATA_LIT_MIN and lit in text and any(_occurrences(text, lit)) \
                        and wlen(_bare(text.replace(lit, ""))) >= 3:
                    fills.append(lit)
                    src.setdefault(lit, set()).add(f)
            continue
        mask, by_tpl = None, False
        for parts in tpls:
            hit = template_match(parts, text, ents)
            if not hit:
                continue
            mask, by_tpl = mask or [False] * n, True
            strong = sum(wlen(p.strip()) for p in parts) >= LOOSE_MIN
            for s, e in hit[0]:
                _mark(mask, s, e)
                if strong:
                    _mark(glue, s, e)
            fills += [fl for fl in hit[1] if 0 < wlen(fl) <= FILL_MAX]
        for lit in {x.strip() for x in lits}:
            # 拉丁文单个词(「Residential」)多半是键名、标签,不算措辞;要词组
            if wlen(lit) >= LIT_MIN and lit in text and (" " in lit or any(_cjk(c) for c in lit)):
                for s, e in _occurrences(text, lit):
                    mask = mask or [False] * n
                    _mark(mask, s, e)
        if mask:
            marks[f] = (mask, by_tpl)
    data_vals, data_files = [], set()
    for fl in set(fills):
        spans = list(_occurrences(text, fl))
        if spans and not any(glue[k] for s, e in spans for k in range(s, e)):
            data_vals.append(fl)
            data_files |= src.get(fl, set())
            for s, e in spans:
                _mark(data, s, e)
    weight = [0 if data[k] or not text[k].strip() else (2 if _cjk(text[k]) else 1) for k in range(n)]
    total = sum(weight)
    cover = {}
    if total >= 3:
        for f, (mask, by_tpl) in marks.items():
            got = sum(w for w, m in zip(weight, mask) if m)
            # 没有模板套上、只靠零散字面量时,要几乎整段措辞都由它写才算(一两个词组撞上不算)
            if got >= 3 and (by_tpl or got >= LIT_FULL * total):
                cover[f] = got / total
    return cover, data_vals, data_files


AFFIX_SEP = re.compile(r"\s+[·|\-\u2014\u2013]\s+")


def strip_site_affix(text):
    """「页面标题 · 站名」→「页面标题」:站名后缀由全站共用的模板加,拿它套模板会命中每一页。"""
    parts = AFFIX_SEP.split(text)
    if len(parts) > 1 and wlen(parts[-1]) <= 30:
        return AFFIX_SEP.split(text, maxsplit=len(parts) - 2)[0] if len(parts) > 2 else parts[0]
    return text


def anchor_candidates(repo, url, anchors, closure=(), root=""):
    """按原文片段反查:每个锚点给命中它的文件记 权重 / 命中文件数;一个锚点对一个文件只记一次最好的片段。"""
    corpus = repo.corpus(root)
    words = url_words(url)
    scores, kinds, cache, solid = {}, {}, {}, set()      # solid:有过不止实体词的证据
    titled = set()                                        # 标题类(title / H1 / og:title)有实打实的证据
    owners, data, data_files, templated = {}, set(), set(), set()
    if closure:                                           # 先分清原文里哪些是数据值、哪些措辞由谁写
        for kind, text in anchors.items():
            if kind == "p":
                continue
            cover, vals, dfiles = explain(repo, closure, strip_site_affix(text) if kind in TITLE_KINDS else text,
                                          words)
            owners[kind] = cover
            data.update(vals)
            data_files |= dfiles
    data = sorted(data, key=len, reverse=True)
    for kind, text in anchors.items():
        best = {}
        # 数据值只在它是这段原文「一部分」时才算数据;整段原文就是它(标题直接取自表里那一格),那是内容本身
        own = strip_site_affix(text) if kind in TITLE_KINDS else text
        kdata = [d for d in data if d in own and wlen(_bare(own.replace(d, ""))) >= 3]
        for frag in fragments(text, words):
            if frag not in cache:
                cache[frag] = [f for f, t in corpus.items() if frag in t]
            hits = cache[frag]
            if not hits or len(hits) > FRAG_MAX_FILES:
                continue
            weak = entity_only(frag, words, kdata)
            w = ANCHOR_WEIGHT.get(kind, 1.0) * (ENTITY_ONLY if weak else 1.0)
            if not w:
                continue
            for f in hits:
                best[f] = max(best.get(f, 0), w / len(hits))
                if not weak:
                    solid.add(f)
                    if kind in TITLE_KINDS:
                        titled.add(f)
        # 措辞由谁写:import 链里字面量和模板解释得最多的文件(并列太多 = 公共套话,不算)
        cover = owners.get(kind) or {}
        top = max(cover.values(), default=0)
        lead = [f for f, c in cover.items() if c >= max(OWNER_MIN, 0.9 * top)]
        for f in lead if len(lead) <= FRAG_MAX_FILES else ():
            best[f] = max(best.get(f, 0), OWNER_GAIN * ANCHOR_WEIGHT.get(kind, 1.0) * cover[f] / len(lead))
            solid.add(f)
            templated.add(f)
            if kind in TITLE_KINDS:
                titled.add(f)
        for f, v in best.items():
            scores[f] = scores.get(f, 0) + v
            kinds.setdefault(f, set()).add(kind)
    if not scores:
        return []
    loc = url_locale(url)
    closure = set(closure)
    zh = {"zh", "zh-cn", "zh-CN"}
    for f in scores:
        if f in closure:
            scores[f] *= 1.5
        fl = file_locales(f)
        if loc and fl:
            if loc in fl:
                scores[f] *= 1.2
            elif not (fl & zh and loc.startswith("zh")):
                scores[f] *= 0.4                              # /es/ 页面却在 en/ 目录里:多半是另一种语言的同文
        elif not loc and fl and fl - zh:
            scores[f] *= 0.6                                  # 无语言前缀(默认语言)页面,别挑外语目录
    # 找的是「改这页标题去哪个文件」:标题类证据实打实的文件排在只有描述、正文证据的文件前面
    ranked = sorted(scores.items(), key=lambda kv: (kv[0] not in titled, -kv[1]))
    total = sum(v for _, v in ranked)
    out = []
    for f, v in ranked[:8]:
        share = v / total
        strong = bool(kinds[f] & {"title", "h1", "description"})
        conf = 0.45 + 0.5 * share if strong else 0.3 + 0.3 * share
        if f not in solid:
            conf = min(conf, 0.6)                             # 只有实体词撞上:不够动手
        elif f not in titled:
            conf = min(conf, 0.6)                             # 没有标题类证据:可能只管描述或正文,不够动手
        for c in classify_data(repo, f):
            c = dict(c)
            if c["role"] == "data" and PAGE_RE.search(f):
                c["role"] = "route"
            c.update(confidence=round(min(0.95, conf if c["role"] != "generated" else 0.3), 2),
                     matched=sorted(kinds[f]), via="page-text+template" if f in templated else "page-text")
            out.append(c)
    # 多源拼接:措辞在模板里,名字(平台名、能力名)来自生成的数据表。把表的真源也列出来,配成「模板 + 真源」
    if out and out[0]["file"] in templated:
        have = {c["file"] for c in out}
        for f in sorted(data_files):
            for c in classify_data(repo, f):
                fl = file_locales(c["file"])
                if c["file"] in have or (fl and not (loc in fl if loc else fl <= zh)):
                    continue                                  # 别的语言那份表管不到这页
                have.add(c["file"])
                out.append(dict(c, confidence=0.3 if c["role"] == "generated" else 0.35, via="data-value",
                                note="页面上的名字来自这里(数据值);改措辞去改模板,名字错了改这份的真源"
                                if c["role"] != "generated" else c.get("note")))
    return out


# ---------- Next.js App Router ----------

def app_routes(files):
    """→ [(segments, file)];segments 每段是 ("static", "x") / ("dyn", name) / ("catch", name) / ("optcatch", name)。"""
    routes = []
    for f in files:
        if not PAGE_RE.search(f):
            continue
        parts = f.split("/")
        try:
            i = max(k for k, p in enumerate(parts[:-1]) if p == "app")
        except ValueError:
            continue
        segs, ok = [], True
        for p in parts[i + 1:-1]:
            if p.startswith("(") and p.endswith(")"):
                continue                                     # 路由组不进 URL
            if p.startswith("_") or p.startswith("@"):
                ok = False                                   # 私有目录 / 并行路由槽
                break
            m = re.fullmatch(r"\[\[\.\.\.(\w+)\]\]", p) or None
            if m:
                segs.append(("optcatch", m.group(1)))
                continue
            m = re.fullmatch(r"\[\.\.\.(\w+)\]", p)
            if m:
                segs.append(("catch", m.group(1)))
                continue
            m = re.fullmatch(r"\[(\w+)\]", p)
            if m:
                segs.append(("dyn", m.group(1)))
                continue
            segs.append(("static", p))
        if ok:
            routes.append((segs, f))
    return routes


def match_route(segs, path_parts):
    """→ (分数, 绑定) 或 None。静态段 3 分、动态段 1 分、捕获 0.5 分。"""
    score, binds, i = 0.0, {}, 0
    for k, (kind, name) in enumerate(segs):
        if kind == "static":
            if i >= len(path_parts) or path_parts[i] != name:
                return None
            score += 3
            i += 1
        elif kind == "dyn":
            if i >= len(path_parts):
                return None
            binds[name] = path_parts[i]
            score += 1
            i += 1
        else:
            rest = path_parts[i:]
            if kind == "catch" and not rest:
                return None
            binds[name] = "/".join(rest)
            score += 0.5
            i = len(path_parts)
            if k != len(segs) - 1:
                return None
    if i != len(path_parts):
        return None
    return score, binds


# 也认 `export { X } from "./y"` 这种转出(桶文件):漏了它,路由的 import 链在第一层就断了
IMPORT_RE = re.compile(r"""(?:\b(?:import|export)[^'"]*?\bfrom\s*|import\s*\(\s*|require\(\s*|import\s+)['"]([^'"]+)['"]""")
RESOLVE_EXT = ("", ".ts", ".tsx", ".js", ".jsx", ".mjs", ".json", "/index.ts", "/index.tsx", "/index.js")


def app_root(route_file):
    parts = route_file.split("/")
    i = max(k for k, p in enumerate(parts[:-1]) if p == "app")
    return "/".join(parts[:i])


def resolve_import(spec, from_file, root, files):
    if spec.startswith("@/") or spec.startswith("~/"):
        base = (root + "/" if root else "") + spec[2:]
    elif spec.startswith("."):
        base = os.path.normpath(os.path.join(os.path.dirname(from_file), spec))
    else:
        return None                                   # 包依赖,不是站点自己的文件
    for ext in RESOLVE_EXT:
        if base + ext in files:
            return base + ext
    return None


def import_closure(repo, route_file, depth=5, cap=400):
    """路由文件按 import 往下走 depth 层,收集站点自己的文件(动态页的数据多半在这里)。"""
    files = set(repo.files())
    root = app_root(route_file)
    seen, frontier, order = {route_file}, [route_file], []
    for _ in range(depth):
        nxt = []
        for f in frontier:
            for spec in IMPORT_RE.findall(repo.read(f)):
                tgt = resolve_import(spec, f, root, files)
                if tgt and tgt not in seen:
                    seen.add(tgt)
                    nxt.append(tgt)
                    order.append(tgt)
        frontier = nxt[:cap]
        if len(order) >= cap:
            break
    return order


def roots_of(value):
    out = [value]
    for suf in STRIP_SUFFIX:
        if value.endswith(suf) and len(value) > len(suf) + 1:
            out.append(value[: -len(suf)])
    return out


def data_candidates(repo, binds, route_file):
    """先在路由文件 import 闭包里找含动态段值的文件(可信);找不到再全仓搜(只作候选)。"""
    closure = import_closure(repo, route_file)
    tokens = [t for v in binds.values() for t in roots_of(v.split("/")[-1]) if len(t) >= 3]
    hits = []
    for f in closure:
        text = repo.read(f)
        for t in tokens:
            if ('"%s"' % t) in text or ("'%s'" % t) in text or ("/%s" % t) in text:
                hits.append((f, t, "import"))
                break
    if hits:
        return hits
    seen, cands = set(), []
    for name, value in binds.items():
        for token in roots_of(value.split("/")[-1]):
            if len(token) < 3:
                continue
            for needle in ('"%s"' % token, "'%s'" % token):
                for f in repo.grep_fixed(needle):
                    if f in seen or f == route_file or "/test" in f or f.endswith((".test.ts", ".test.tsx")):
                        continue
                    seen.add(f)
                    cands.append((f, token, "grep"))
    return cands


def classify_data(repo, f):
    head = repo.head(f)
    if not GEN_MARK.search(head):
        return [{"file": f, "role": "data"}]
    out = [{"file": f, "role": "generated", "note": "生成物,手改会被覆盖"}]
    files = set(repo.files())
    for m in GEN_SCRIPT.finditer(head):
        cand = m.group(1).lstrip("./")
        for path in (cand, os.path.normpath(os.path.join(os.path.dirname(f), cand))):
            if path in files and path != f:
                out.append({"file": path, "role": "generator"})
                break
    return out


def map_next(repo, url, routes):
    path = urllib.parse.urlsplit(url).path
    parts = [urllib.parse.unquote(p) for p in path.strip("/").split("/") if p]
    best = []
    for segs, f in routes:
        m = match_route(segs, parts)
        if m:
            best.append((m[0], m[1], f))
    if not best:
        return None
    best.sort(key=lambda x: -x[0])
    top = [b for b in best if b[0] == best[0][0]]
    _, binds, route_file = top[0]
    ambiguous = len(top) > 1
    cands = []
    if not binds:
        cands.append({"file": route_file, "role": "route", "confidence": 0.5 if ambiguous else 0.95})
    else:
        cands.append({"file": route_file, "role": "route", "confidence": 0.55})
        data = data_candidates(repo, binds, route_file)
        # 离路由目录近、在 content/lib/data 下的排前面;生成物换成生成器
        def rank(item):
            f = item[0]
            near = 0 if any(d in f for d in ("content/", "lib/", "data/", "/scripts/")) else 1
            return (near, f.count("/"), f)
        data.sort(key=rank)
        n = len(data)
        for f, token, how in data[:6]:
            for c in classify_data(repo, f):
                if how == "import":
                    base = 0.9 if n <= 2 else 0.75
                else:
                    base = 0.5 if n <= 2 else 0.35
                if c["role"] == "generated":
                    base = 0.3
                elif c["role"] == "generator":
                    base = min(0.9, base + 0.05)
                c.update(confidence=round(base, 2), matched=token)
                cands.append(c)
    for c in top[1:]:
        cands.append({"file": c[2], "role": "route", "confidence": 0.4, "note": "同分的另一条路由"})
    return cands


# ---------- 静态站 ----------

def map_static(repo, url):
    files = set(repo.files())
    path = urllib.parse.urlsplit(url).path.strip("/")
    tries = []
    for root in STATIC_ROOTS:
        if not path:
            tries.append(root + "index.html")
        else:
            tries += [root + path + "/index.html", root + path + ".html", root + path]
    hits = [t for t in tries if t in files and t.endswith((".html", ".htm"))]
    return [{"file": h, "role": "route", "confidence": 0.95 if k == 0 else 0.6} for k, h in enumerate(hits)]


def detect(repo):
    routes = app_routes(repo.files())
    if routes:
        return "next-app-router", routes
    if any(f.endswith(".html") for f in repo.files()):
        return "static", None
    return None, None


def merge(text_cands, route_cands):
    """原文命中优先;路由办法的候选排在后面作补充,同一文件只留置信度高的一条。"""
    seen, out = {}, []
    for c in text_cands + route_cands:
        k = (c["file"], c["role"])
        if k in seen:
            continue
        seen[k] = True
        out.append(c)
    return out


def map_urls(repo, urls, min_conf=0.7, anchors_for=None):
    """anchors_for(url) → {title, description, h1, ...};None 时不看页面,只用路由办法。"""
    kind, routes = detect(repo)
    out = []
    for u in urls:
        if kind == "next-app-router":
            cands = map_next(repo, u, routes) or []
        elif kind == "static":
            cands = map_static(repo, u)
        else:
            cands = []
        anchors = anchors_for(u) if anchors_for else {}
        if anchors and kind:
            closure, root = (), ""
            route_files = [c["file"] for c in cands if c["role"] == "route"]
            if kind == "next-app-router":
                root = site_root(route_files[0] if route_files else routes[0][1])
                if route_files:
                    closure = import_closure(repo, route_files[0])
            text = anchor_candidates(repo, u, anchors, closure, root)
            if text:
                sure_route = {c["file"] for c in cands if c["confidence"] >= 0.9}
                for c in cands:                               # 原文找到了,路由办法的猜测降级为参考
                    c["confidence"] = round(min(c["confidence"], 0.5 if c["role"] == "route" else 0.4), 2)
                if text[0]["file"] in sure_route:             # 两种办法指向同一个文件:可信
                    text[0]["confidence"] = 0.95
                    text[0]["via"] = "page-text+route"
                cands = merge(text, cands)
        cands.sort(key=lambda c: -c["confidence"])
        best = cands[0]["confidence"] if cands else 0.0
        row = {"url": u, "framework": kind or "unsupported", "candidates": cands,
               "best": cands[0]["file"] if cands else None, "confidence": best,
               "actionable": best >= min_conf and cands[0]["role"] != "generated"}
        data_src = [c["file"] for c in cands if c.get("via") == "data-value" and c["role"] != "generated"]
        if cands and "template" in cands[0].get("via", "") and data_src:
            row["combo"] = {"template": cands[0]["file"], "data": data_src}
        out.append(row)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(prog="source_map.py", description="线上 URL → 源文件")
    ap.add_argument("urls", nargs="+")
    ap.add_argument("--repo", required=True)
    ap.add_argument("--rev", help="读某个提交(如 origin/main),不用检出")
    ap.add_argument("--min-confidence", type=float, default=0.7)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--no-fetch", action="store_true", help="不抓线上页面,只按路由和动态段找")
    ap.add_argument("--fetch-base", help="抓页面时把 URL 的协议+主机换成这个(比如本地预览 http://127.0.0.1:3000)")
    ns = ap.parse_args(argv)
    if not os.path.isdir(ns.repo):
        sys.stderr.write("source_map.py: --repo 不是目录\n")
        return 2

    def anchors_for(u):
        if ns.fetch_base:
            sp = urllib.parse.urlsplit(u)
            u = ns.fetch_base.rstrip("/") + sp.path + ("?" + sp.query if sp.query else "")
        return fetch_anchors(u)
    res = map_urls(Repo(ns.repo, ns.rev), ns.urls, ns.min_confidence, None if ns.no_fetch else anchors_for)
    if ns.json:
        print(json.dumps({"results": res}, ensure_ascii=False, indent=1))
    else:
        for r in res:
            print("%s → %s(%.2f%s)" % (r["url"], r["best"], r["confidence"], "" if r["actionable"] else ",只列候选"))
            if r.get("combo"):
                print("    模板 %s + 数据真源 %s" % (r["combo"]["template"], "、".join(r["combo"]["data"])))
            for c in r["candidates"][1:5]:
                print("    %s [%s %.2f]" % (c["file"], c["role"], c["confidence"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
